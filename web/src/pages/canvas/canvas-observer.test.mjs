test("只读查看页渲染插件节点及上游内容，不显示插件缺失", async (t) => {
    const server = await createServer({ root: fileURLToPath(new URL("../../../", import.meta.url)), server: { middlewareMode: true, hmr: false, ws: false }, optimizeDeps: { noDiscovery: true, include: [] } });
    const previousStorage = globalThis.localStorage;
    globalThis.localStorage = { getItem: () => null, setItem() {} };
    t.after(async () => { globalThis.localStorage = previousStorage; await server.close(); });
    const { registerNodeDefinitions } = await server.ssrLoadModule("/src/lib/canvas/node-registry.ts");
    const { useCanvasObserverStore } = await server.ssrLoadModule("/src/stores/canvas/use-canvas-observer-store.ts");
    const { CanvasObserver } = await server.ssrLoadModule("/src/pages/canvas/canvas-observer.tsx");
    registerNodeDefinitions([{ type: "test:preview", title: "预览插件", icon: "", defaultSize: { width: 300, height: 200 }, Content: ({ ctx }) => React.createElement("div", null, ctx.node.metadata.content, ctx.getUpstream().map((node) => node.metadata.content).join("")) }], "test");
    const node = (id, type, content) => ({ id, type, position: { x: 0, y: 0 }, width: 300, height: 200, metadata: { content } });
    Object.assign(useCanvasObserverStore.getInitialState(), { projectId: "watched", connected: true, controls: [{ projectId: "watched", clientId: "owner", sessionId: "owner-session", title: "观战" }], snapshot: { projectId: "watched", title: "观战", nodes: [node("upstream", "text", "上游内容"), node("plugin", "test:preview", "插件预览已渲染")], connections: [{ id: "edge", fromNodeId: "upstream", toNodeId: "plugin" }], selectedNodeIds: [], viewport: { x: 0, y: 0, k: 1 } } });
    const html = renderToStaticMarkup(React.createElement(MemoryRouter, null, React.createElement(CanvasObserver, { projectId: "watched", onEdit() {} })));
    assert.ok(html.includes("插件预览已渲染"), "插件节点应使用注册的渲染器");
    assert.ok(html.includes("插件预览已渲染上游内容"), "插件渲染器应能读取当前快照中的上游节点");
    assert.ok(!html.includes("缺少插件"), "已注册插件不应显示缺少插件");
    assert.match(html, /inert=""/);
});

test("观察插件的查询返回副本，写入、生成、事件和持久化均不影响原状态", async (t) => {
    const server = await createServer({ root: fileURLToPath(new URL("../../../", import.meta.url)), server: { middlewareMode: true, hmr: false, ws: false }, optimizeDeps: { noDiscovery: true, include: [] } });
    const previousStorage = globalThis.localStorage;
    globalThis.localStorage = { getItem: () => null, setItem() {} };
    t.after(async () => { globalThis.localStorage = previousStorage; await server.close(); });
    const disk = new Map([["setting", "原设置"]]);
    t.mock.method(localforage, "createInstance", () => ({ getItem: async (key) => disk.get(key), setItem: async (key, value) => disk.set(key, value), removeItem: async (key) => disk.delete(key) }));
    const { createCanvasObserverHost } = await server.ssrLoadModule("/src/pages/canvas/canvas-observer-host.ts");
    const { buildNodeContext } = await server.ssrLoadModule("/src/lib/canvas/plugin-node-context.ts");
    const { emitCanvasEvent, onCanvasEvent } = await server.ssrLoadModule("/src/lib/canvas/canvas-event-bus.ts");
    const nodes = ["upstream", "plugin", "downstream"].map((id) => ({ id, type: "test:preview", title: id, metadata: { content: id } }));
    const connections = [{ id: "a", fromNodeId: "upstream", toNodeId: "plugin" }, { id: "b", fromNodeId: "plugin", toNodeId: "downstream" }];
    const original = JSON.stringify({ nodes, connections });
    const host = createCanvasObserverHost(nodes, connections);
    const ctx = buildNodeContext(host, nodes[1], {}, 1);
    assert.deepEqual(ctx.getUpstream().map((node) => node.id), ["upstream"]);
    assert.deepEqual(ctx.getDownstream().map((node) => node.id), ["downstream"]);
    ctx.node.metadata.content = "直接修改";
    ctx.getNode("plugin").title = "修改查询结果";
    ctx.getNodes()[0].metadata.content = "修改节点列表";
    ctx.getConnections()[0].toNodeId = "修改连线";
    ctx.getUpstream()[0].metadata.content = "修改上游";
    ctx.getDownstream()[0].metadata.content = "修改下游";
    ctx.updateMetadata({ content: "写入" });
    ctx.updateNode({ title: "重命名" });
    ctx.applyOps([{ type: "delete_node", id: "plugin" }]);
    ctx.openPanel(); ctx.closePanel();
    assert.equal(JSON.stringify({ nodes, connections }), original);
    for (const generate of [ctx.ai.generateImage, ctx.ai.generateVideo, ctx.ai.generateText]) await assert.rejects(generate("生成"), /只读/);
    let received = 0;
    const unsubscribe = onCanvasEvent("observe-test", () => received++);
    t.after(unsubscribe);
    ctx.emit("observe-test");
    assert.equal(received, 0);
    const stop = ctx.on("observe-test", () => assert.fail("观察节点不能接入编辑事件"));
    emitCanvasEvent("observe-test"); stop();
    assert.equal(received, 1);
    assert.equal(await ctx.storage.get("setting"), "原设置");
    await ctx.storage.set("setting", "不应保存");
    await ctx.storage.remove("setting");
    assert.equal(disk.get("setting"), "原设置");

    let edits = 0;
    const editor = buildNodeContext({ ...host, readOnly: false, updateMetadata: () => edits++ }, nodes[1], {}, 1);
    editor.updateMetadata({ content: "正常编辑" });
    editor.emit("observe-test");
    await editor.storage.set("setting", "编辑设置");
    assert.equal(edits, 1);
    assert.equal(received, 2);
    assert.equal(disk.get("setting"), "编辑设置");
});
